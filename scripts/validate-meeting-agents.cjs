const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { researchMeeting } = require('../dist/main/meetingResearch')
const { collectMeetingProject } = require('../dist/main/meetingProjectContext')
const { isPathSafe } = require('../dist/main/workspaceSafetyGuard')
async function main() {
  const root = path.resolve(__dirname, '../.whisper-validation/meeting-project')
  await fs.mkdir(root, { recursive: true })
  await fs.mkdir(root + '-outside', { recursive: true })
  await fs.writeFile(path.join(root + '-outside', 'secret.txt'), 'outside fixture')
  await fs.writeFile(path.join(root, '.env'), 'API_KEY=do-not-send-fixture')
  await fs.writeFile(path.join(root, 'authorization.ts'), "export function authorizeMeeting(role: string) { return role === 'moderator' }\n")
  const signal = new AbortController().signal
  const evidence = await collectMeetingProject(root, 'authorizeMeeting moderator', signal)
  assert.equal(isPathSafe(root, path.join(root + '-outside', 'secret.txt')), false)
  assert.ok(evidence.sources.some(source => source.title === 'authorization.ts'))
  assert.ok(!JSON.stringify(evidence).includes('do-not-send-fixture'))
  const result = await researchMeeting({ id: 'integration', scope: 'both', projectPath: root, question: 'Como o Electron controla permissões de mídia? Compare com a regra authorizeMeeting de authorization.ts e explique quais papéis ela aceita.' }, signal, console.log)
  await fs.writeFile(path.resolve(__dirname, '../.whisper-validation/meeting-combined-result.json'), JSON.stringify(result, null, 2))
  assert.ok(result.sources.some(source => source.type === 'web'))
  assert.ok(result.sources.some(source => source.type === 'project'))
  assert.match(result.findings, /moderator|moderador/i)
  await fs.writeFile(path.join(root, 'authorization.ts'), "export function authorizeMeeting(role: string) { return role === 'owner' }\n")
  const fresh = await collectMeetingProject(root, 'authorizeMeeting', signal)
  assert.match(fresh.sources[0].snippet, /owner/)
  assert.ok(!fresh.sources[0].snippet.includes('moderator'))
  const report = await researchMeeting({ id: 'report', scope: 'report', question: 'Gere um relatório sobre a análise de permissões desta reunião.', context: 'Decidimos revisar permissões antes da próxima versão.', previousReport: result.findings }, signal, console.log)
  assert.match(report.findings, /permiss|revis/i)
  const controller = new AbortController(); controller.abort()
  await assert.rejects(() => researchMeeting({ id: 'cancelled', scope: 'project', projectPath: root, question: 'Analise authorizeMeeting.' }, controller.signal, () => {}))
  await fs.writeFile(path.resolve(__dirname, '../.whisper-validation/meeting-agents-result.json'), JSON.stringify({ result, report, freshFolderVerified: true, secretExcluded: true, siblingBlocked: true, cancellationVerified: true }, null, 2))
  console.log(JSON.stringify({ passed: true, sources: result.sources.length, reportCharacters: report.findings.length }))
}
main().catch(error => { console.error(error); process.exitCode = 1 })
